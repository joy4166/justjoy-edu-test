export function getAidSimpleTitle(dept) {
  if (!dept) return '부서 활동지';
  if (dept.id === '02_elem_lower' && dept.aid_format && dept.aid_format.code === '형식 B') {
    return '초등1부 도감활동지';
  }
  return AID_SIMPLE_TITLES[dept.id] || `${dept.name} 활동지`;
}
